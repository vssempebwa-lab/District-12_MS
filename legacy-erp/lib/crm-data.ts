export type DealStage =
  | "lead"
  | "qualified"
  | "proposal"
  | "negotiation"
  | "won"
  | "lost";

export interface DealStageMeta {
  id: DealStage;
  label: string;
  color: string;
  soft: string;
  text: string;
}

