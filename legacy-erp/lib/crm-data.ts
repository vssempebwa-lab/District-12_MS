export const openStages: DealStage[] = [
  "lead",
  "qualified",
  "proposal",
  "negotiation",
];

export function stageMeta(stage: DealStage) {
  return dealStages.find((item) => item.id === stage) ?? dealStages[0];
}

export function nextStage(stage: DealStage): DealStage | null {
  const order: DealStage[] = ["lead", "qualified", "proposal", "negotiation", "won"];
  const index = order.indexOf(stage);
  if (index === -1 || index === order.length - 1) return null;
  return order[index + 1];
}

export function stageProbability(stage: DealStage) {
  switch (stage) {
    case "lead":
      return 15;
    case "qualified":
      return 35;
    case "proposal":
      return 60;
    case "negotiation":
      return 80;
    case "won":
      return 100;
    default:
      return 0;
  }
}

